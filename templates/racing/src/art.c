const char size_w[NSIZES] = { 4, 8, 12, 16, 20, 24 };   // pixels (even: multicolour)
const char size_h[NSIZES] = { 3, 5, 8, 10, 13, 16 };

// Opponent picture k: its rows at the sprite's top (the small ones) or
// ending on row 20 (the big ones): road.c's top_aligned.
static void car_picture(char k, const char *src)
{
    char *d = SPRITES + k * 64;
    memset(d, 0, 64);
    char h = size_h[k];
    char first = k < 3 ? 0 : 21 - h;
    memcpy(d + first * 3, src, h * 3);
}

// The player's car, lean l (0 straight, 1 left, 2 right): rows 0-5, the
// roof and window, one pixel toward the turn; the body still. Into blocks
// PL_PTR0 + 3l, + 1, + 2 (left, middle, right).
static void player_picture(char l)
{
    char *d = SPRITES + (ASM_PL_PTR0 - 48 + 3 * l) * 64;
    for (char r = 0; r < 21; r++)
    {
        char row[9];
        memcpy(row, player_bytes + r * 9, 9);
        char carry = 0;
        if (r < 6 && l == 1)            // one pair left: the 72 bits << 2
        {
            char i = 9;
            while (i)
            {
                i--;
                char v = row[i];
                row[i] = (v << 2) | carry;
                carry = v >> 6;
            }
        }
        else if (r < 6 && l == 2)       // one pair right: >> 2
            for (char i = 0; i < 9; i++)
            {
                char v = row[i];
                row[i] = (v >> 2) | carry;
                carry = v << 6;
            }
        for (char c = 0; c < 3; c++)
            memcpy(d + c * 64 + r * 3, row + c * 3, 3);
    }
}

void art_init(void)
{
    // The ROM's upper-case set, 256 characters with the reversed half, for
    // the panel and the meter.
    *(volatile char *)1 = 0x33;         // character ROM in at $D000
    for (unsigned i = 0; i < 2048; i++)
        HUDFONT[i] = ((char *)0xd000)[i];
    *(volatile char *)1 = 0x35;         // I/O back; BASIC and KERNAL stay out

    const char *src = opp_bytes;
    for (char k = 0; k < NSIZES; k++)
    {
        car_picture(k, src);
        src += size_h[k] * 3;
    }
    for (char l = 0; l < 3; l++)
        player_picture(l);
}

// The sky rows of a road screen: blank, then hills on rows 5 and 6.
void art_sky(char *screen)
{
    static const char hills[20] = {
        0, 0, 3, 2, 4, 0, 0, 0, 3, 2, 2, 4, 0, 0, 0, 0, 3, 4, 0, 0
    };
    memset(screen, 0, 7 * 40);
    for (char c = 0; c < 40; c++)
    {
        char k = c % 20;
        screen[6 * 40 + c] = hills[k];
        screen[5 * 40 + c] = k == 9 ? CH_HILL + 1 : k == 10 ? CH_HILL + 2 : 0;
    }
}
